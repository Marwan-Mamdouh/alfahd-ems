import axios from "axios";
import { api, unwrap } from "@/core/api/axios-instance";
import { ENDPOINTS } from "@/core/api/endpoints";
import type {
  JobStatusResponseDto,
  AttendanceQueryDto,
  RouterReportQueryDto,
} from "@/core/api/types";

/**
 * Fetch status, progress, and results of an asynchronous background job.
 */
export async function fetchJobStatus(jobId: string): Promise<JobStatusResponseDto> {
  const response = await api.get<{ data: JobStatusResponseDto }>(ENDPOINTS.jobs.status(jobId));
  return unwrap(response);
}

/**
 * Poll status specifically through the IP import status route (`GET /ip-addresses/import/:id`).
 */
export async function fetchIpImportStatus(jobId: string): Promise<JobStatusResponseDto> {
  const response = await api.get<{ data: JobStatusResponseDto }>(
    ENDPOINTS.ipAddresses.importStatus(jobId)
  );
  return unwrap(response);
}

/**
 * Enqueue an asynchronous attendance report (`GET /attendance/report`).
 */
export async function enqueueAttendanceReport(
  query?: AttendanceQueryDto
): Promise<{ jobId: string }> {
  const response = await api.get<{ data: { jobId: string } }>(ENDPOINTS.attendance.report, {
    params: query,
  });
  return unwrap(response);
}

/**
 * Enqueue an asynchronous router inventory Excel export (`POST /routers/export`).
 */
export async function enqueueRouterExport(
  dto?: RouterReportQueryDto
): Promise<{ jobId: string }> {
  const response = await api.post<{ data: { jobId: string } }>(
    ENDPOINTS.routers.export,
    dto ?? {}
  );
  return unwrap(response);
}

/**
 * Upload a CSV file as multipart form-data to enqueue an IP address import job (`POST /ip-addresses/import`).
 */
export async function uploadIpCsvFile(file: File): Promise<{ jobId: string }> {
  return uploadCsvFile(ENDPOINTS.ipAddresses.import, file);
}

/**
 * Upload a CSV file as multipart form-data to any enqueuing endpoint.
 */
export async function uploadCsvFile(
  endpoint: string,
  file: File
): Promise<{ jobId: string }> {
  const formData = new FormData();
  formData.append("file", file);

  const response = await api.post<{ data: { jobId: string } }>(endpoint, formData);
  return unwrap(response);
}

/**
 * Extract the Content-Disposition header regardless of casing or AxiosHeaders accessor.
 */
function getContentDisposition(headers: unknown): string | undefined {
  if (!headers || typeof headers !== "object") return undefined;
  if ("get" in headers && typeof (headers as { get: (name: string) => unknown }).get === "function") {
    const val = (headers as { get: (name: string) => unknown }).get("content-disposition");
    if (typeof val === "string") return val;
  }
  const rec = headers as Record<string, unknown>;
  const val = rec["content-disposition"] ?? rec["Content-Disposition"];
  return typeof val === "string" ? val : undefined;
}

/**
 * Parses a filename from a Content-Disposition header according to RFC 6266 and RFC 5987.
 *
 * Checks in precedence order:
 * 1. RFC 5987 filename*=charset'lang'encoded-value (e.g. filename*=UTF-8''%D8%AA%D9%82%D8%B1%D9%8A%D8%B1.xlsx)
 * 2. Quoted standard filename="name.xlsx"
 * 3. Bare standard filename=name.xlsx
 *
 * If missing, invalid, or path-traversal only, falls back to `fallback`.
 */
export function parseContentDispositionFilename(
  header?: string | null,
  fallback = "report.xlsx"
): string {
  if (!header || typeof header !== "string") {
    return fallback;
  }

  // 1. RFC 5987 filename*=charset'lang'encoded-value
  const rfc5987Match = header.match(/filename\*\s*=\s*([^';]+)''([^;\s]+)/i);
  if (rfc5987Match && rfc5987Match[2]) {
    try {
      const decoded = decodeURIComponent(rfc5987Match[2].trim());
      const sanitized = decoded.replace(/^.*[\\/]/, "").trim();
      if (sanitized) return sanitized;
    } catch {
      // Decode failure, fall through to standard filename
    }
  }

  // 2. Quoted filename="..."
  const quotedMatch = header.match(/filename\s*=\s*"([^"]+)"/i);
  if (quotedMatch && quotedMatch[1]) {
    const sanitized = quotedMatch[1].replace(/^.*[\\/]/, "").trim();
    if (sanitized) return sanitized;
  }

  // 3. Unquoted filename=...
  const unquotedMatch = header.match(/filename\s*=\s*([^;\s]+)/i);
  if (unquotedMatch && unquotedMatch[1]) {
    const cleaned = unquotedMatch[1].replace(/["']/g, "").replace(/^.*[\\/]/, "").trim();
    if (cleaned) return cleaned;
  }

  return fallback;
}

/**
 * Download a binary Excel report generated by a completed job.
 * Handles both API-relative local report downloads (`/jobs/:id/download`) with bearer auth
 * and approved external provider URLs (pre-signed S3 / Cloudinary) without sending bearer tokens to external origins.
 *
 * Automatically parses `Content-Disposition` for the server-sent filename with `fallbackFilename`
 * ("report.xlsx" by default) as fallback when the header is absent.
 */
export async function downloadReportFile(
  downloadUrlOrJobId: string,
  fallbackFilename = "report.xlsx"
): Promise<void> {
  let blob: Blob;
  let rawContentDisposition: string | undefined;

  const isExternalUrl =
    downloadUrlOrJobId.startsWith("http://") || downloadUrlOrJobId.startsWith("https://");

  if (isExternalUrl) {
    // External approved provider URLs (pre-signed). Do NOT send our API bearer token to external hosts.
    const res = await axios.get<Blob>(downloadUrlOrJobId, {
      responseType: "blob",
    });
    blob = res.data;
    rawContentDisposition = getContentDisposition(res.headers);
  } else {
    // API-relative endpoint (/jobs/:id/download or raw jobId)
    const targetUrl = downloadUrlOrJobId.startsWith("/jobs/")
      ? downloadUrlOrJobId
      : ENDPOINTS.jobs.download(downloadUrlOrJobId);

    const res = await api.get<Blob>(targetUrl, {
      responseType: "blob",
    });
    blob = res.data;
    rawContentDisposition = getContentDisposition(res.headers);
  }

  const filename = parseContentDispositionFilename(rawContentDisposition, fallbackFilename);

  if (typeof window !== "undefined" && typeof document !== "undefined") {
    const objectUrl = window.URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = objectUrl;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    window.URL.revokeObjectURL(objectUrl);
  }
}
