import axios from "axios";
import { api, unwrap, downloadBlob } from "@/core/api/axios-instance";
import { ENDPOINTS } from "@/core/api/endpoints";
import type {
  JobStatusResponseDto,
  AttendanceQueryDto,
  RouterReportQueryDto,
} from "@/core/api/types";

/**
 * Fetch status, progress, and results of an asynchronous background job.
 */
export async function fetchJobStatus(jobId: string): Promise<JobStatusResponseDto> {
  const response = await api.get<{ data: JobStatusResponseDto }>(ENDPOINTS.jobs.status(jobId));
  return unwrap(response);
}

/**
 * Poll status specifically through the IP import status route (`GET /ip-addresses/import/:id`).
 */
export async function fetchIpImportStatus(jobId: string): Promise<JobStatusResponseDto> {
  const response = await api.get<{ data: JobStatusResponseDto }>(
    ENDPOINTS.ipAddresses.importStatus(jobId)
  );
  return unwrap(response);
}

/**
 * Enqueue an asynchronous attendance report (`GET /attendance/report`).
 */
export async function enqueueAttendanceReport(
  query?: AttendanceQueryDto
): Promise<{ jobId: string }> {
  const response = await api.get<{ data: { jobId: string } }>(ENDPOINTS.attendance.report, {
    params: query,
  });
  return unwrap(response);
}

/**
 * Enqueue an asynchronous router inventory Excel export (`POST /routers/export`).
 */
export async function enqueueRouterExport(
  dto?: RouterReportQueryDto
): Promise<{ jobId: string }> {
  const response = await api.post<{ data: { jobId: string } }>(
    ENDPOINTS.routers.export,
    dto ?? {}
  );
  return unwrap(response);
}

/**
 * Upload a CSV file as multipart form-data to enqueue an IP address import job (`POST /ip-addresses/import`).
 */
export async function uploadIpCsvFile(file: File): Promise<{ jobId: string }> {
  return uploadCsvFile(ENDPOINTS.ipAddresses.import, file);
}

/**
 * Upload a CSV file as multipart form-data to any enqueuing endpoint.
 */
export async function uploadCsvFile(
  endpoint: string,
  file: File
): Promise<{ jobId: string }> {
  const formData = new FormData();
  formData.append("file", file);

  const response = await api.post<{ data: { jobId: string } }>(endpoint, formData);
  return unwrap(response);
}

/**
 * Download a binary Excel report generated by a completed job.
 * Handles both API-relative local report downloads (`/jobs/:id/download`) with bearer auth
 * and approved external provider URLs (pre-signed S3 / Cloudinary) without sending bearer tokens to external origins.
 */
export async function downloadReportFile(
  downloadUrlOrJobId: string,
  filename = "report.xlsx"
): Promise<void> {
  let blob: Blob;

  const isExternalUrl =
    downloadUrlOrJobId.startsWith("http://") || downloadUrlOrJobId.startsWith("https://");

  if (isExternalUrl) {
    // External approved provider URLs (pre-signed). Do NOT send our API bearer token to external hosts.
    const res = await axios.get<Blob>(downloadUrlOrJobId, {
      responseType: "blob",
    });
    blob = res.data;
  } else {
    // API-relative endpoint (/jobs/:id/download or raw jobId)
    const targetUrl = downloadUrlOrJobId.startsWith("/jobs/")
      ? downloadUrlOrJobId
      : ENDPOINTS.jobs.download(downloadUrlOrJobId);

    blob = await downloadBlob(targetUrl);
  }

  if (typeof window !== "undefined" && typeof document !== "undefined") {
    const objectUrl = window.URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = objectUrl;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    window.URL.revokeObjectURL(objectUrl);
  }
}
